"""Task-local controlled-worker guards; no service or accounting authority."""
import math
import json
import os
from pathlib import Path
import resource
import signal
import subprocess
import sys
import time


# This OS-only timer runs before Conda/Python startup. Every Python process still
# uses the approved Conda command. Positional parameters never contain shell code.
BOOTSTRAP = r'''
wall=$1
hard_wall=$2
shift 2
(
    soft_sleeper=
    hard_sleeper=
    trap 'if [ -n "$soft_sleeper" ]; then kill "$soft_sleeper" 2>/dev/null; wait "$soft_sleeper" 2>/dev/null; soft_sleeper=; fi; if [ -n "$hard_sleeper" ]; then kill -KILL "$hard_sleeper" 2>/dev/null; wait "$hard_sleeper" 2>/dev/null; hard_sleeper=; fi; exit 0' USR1
    /bin/sleep "$wall" &
    soft_sleeper=$!
    (trap '' TERM; exec /bin/sleep "$hard_wall") &
    hard_sleeper=$!
    wait "$soft_sleeper"
    soft_sleeper=
    # Both children already exist before termination. The caller's identity
    # inventory can learn them while its group leader is still alive; grace
    # never introduces an unrecognized descendant after the leader is reaped.
    trap '' USR1
    trap '' TERM
    kill -TERM -- -$$ 2>/dev/null
    wait "$hard_sleeper"
    hard_sleeper=
    kill -KILL -- -$$ 2>/dev/null
) &
timer=$!
"$@" <&0 &
worker=$!
wait "$worker"
code=$?
worker=
kill -USR1 "$timer" 2>/dev/null
wait "$timer" 2>/dev/null
timer=
exit "$code"
'''


def command(root, module):
    return ['/opt/miniconda3/bin/conda', 'run', '--no-capture-output', '-n', 'nilaris',
            'python', str(root / 'runtime/a1/with_overlay.py'), '-m', module]


def processes(pgid, *, isolate_inventory=False):
    """Real group identities and sampled cumulative CPU/RSS, descendants included."""
    result = subprocess.run(['/bin/ps', '-axo', 'pid=,pgid=,rss=,time=,lstart='],
                            capture_output=True, text=True, timeout=1, check=True,
                            start_new_session=isolate_inventory)
    members = []
    for line in result.stdout.splitlines():
        fields = line.split(None, 4)
        if len(fields) != 5 or int(fields[1]) != pgid:
            continue
        clock = fields[3].split(':')
        seconds = float(clock[-1]) + 60 * int(clock[-2])
        if len(clock) == 3:
            seconds += 3600 * int(clock[0])
        members.append(dict(pid=int(fields[0]), pgid=pgid, rss=int(fields[2]) * 1024,
                            cpu=seconds, start=fields[4]))
    return members


def arm_worker_deadline():
    """Kernel-backed last clock before optional imports or gated graph input.

    The handler signals only this live process's own inherited group. Its PID
    cannot be recycled while this code runs. This is a wall backup, not a hard
    aggregate native resource guarantee or simultaneous-guard-loss protection.
    """
    deadline = float(os.environ['NILARIS_CONTROLLED_DEADLINE'])
    cpu = float(os.environ['NILARIS_CONTROLLED_CPU'])
    if not math.isfinite(deadline) or not 0 < cpu <= 20:
        raise ValueError('invalid lifecycle allowance')
    group = os.getpgrp()

    def expire(signum, frame):
        os.killpg(group, signal.SIGKILL)

    signal.signal(signal.SIGALRM, expire)
    signal.setitimer(signal.ITIMER_REAL, max(.001, deadline + 2 - time.monotonic()))
    resource.setrlimit(resource.RLIMIT_CPU, (math.ceil(cpu), math.ceil(cpu)))
    return dict(pid=os.getpid(), pgid=group,
                monitor_pid=int(os.environ['NILARIS_CONTROLLED_MONITOR']))


def main():
    """Independent nominal-100ms policy monitor, without DB publication rights."""
    deadline = float(os.environ['NILARIS_CONTROLLED_DEADLINE'])
    cpu_limit = float(os.environ['NILARIS_CONTROLLED_CPU'])
    rss_limit = int(os.environ['NILARIS_CONTROLLED_RSS'])
    group = os.getpgrp()
    root = Path(__file__).resolve().parents[2]
    environment = dict(os.environ, NILARIS_CONTROLLED_MONITOR=str(os.getpid()))
    child = subprocess.Popen(command(root, 'nilaris.controlled_stage'), stdin=sys.stdin.buffer,
                             stdout=sys.stdout.buffer, stderr=subprocess.DEVNULL,
                             env=environment)
    # No output or request payload is generated by this monitor. The actual
    # stage emits its bounded readiness header directly to the caller's pipe.
    reason = None
    cpu = rss = 0
    identity = None
    try:
        while child.poll() is None:
            started = time.monotonic()
            members = processes(group)
            identity = next(m for m in members if m['pid'] == os.getpid())
            cpu = sum(m['cpu'] for m in members)
            rss = sum(m['rss'] for m in members)
            if started >= deadline:
                reason = 'attempt_wall_limit'
            elif cpu >= cpu_limit:
                reason = 'attempt_cpu_limit'
            elif rss >= rss_limit:
                reason = 'worker_rss_limit'
            if reason:
                break
            time.sleep(max(0, .1 - (time.monotonic() - started)))
    except Exception:
        # An unavailable inventory is not permission to continue unmonitored.
        reason = 'inventory_unavailable'
    if reason:
        if identity and reason != 'inventory_unavailable':
            receipt = dict(reason=reason, pid=identity['pid'], pgid=group,
                           start=identity['start'], cpu=cpu, rss=rss)
            data = b'NILARIS_WORKER_STOP ' + json.dumps(receipt, separators=(',', ':')).encode() + b'\n'
            if len(data) <= 4096:
                try:
                    os.set_blocking(2, False)
                    os.write(2, data)
                except (BlockingIOError, BrokenPipeError, OSError):
                    pass
        signal.signal(signal.SIGTERM, signal.SIG_IGN)
        os.killpg(group, signal.SIGTERM)
        time.sleep(2)
        os.killpg(group, signal.SIGKILL)
    raise SystemExit(child.wait())


if __name__ == '__main__':
    main()
